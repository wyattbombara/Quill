export const defaultPalette: PaletteName = 'Violet / clay';
export function paletteStyle(
  palette: PaletteName,
  theme: 'light' | 'dark',
): CSSProperties {
  return Object.fromEntries(
    Object.entries(palettes[palette][theme]).map(([key, value]) => [
      '--' + key.replace(/[A-Z]/g, (letter) => '-' + letter.toLowerCase()),
      value,
    ]),
  ) as CSSProperties;
}
export function paletteClass(palette: PaletteName, theme: 'light' | 'dark') {
  return (
    (palette === 'Violet / clay' ? ' liquid-glass' : '') +
    (theme === 'dark' ? ' dark-mode' : '')
  );
}
